/** Writes src/data/ from the GeoThai/data release named in data.version. */
const version = (await Bun.file('data.version').text()).trim();

async function get<T>(path: string): Promise<T> {
  const url = `https://raw.githubusercontent.com/GeoThai/data/${version}/${path}`;
  const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`GeoThai/data ${version}: HTTP ${res.status} for ${path}`);
  return (await res.json()) as T;
}

type Row = { code: string; name_th: string; name_en: string };

// A JSON string parses faster than the same data as a JS literal.
async function write(level: string, rows: unknown[], type: string) {
  await Bun.write(
    `src/data/${level}.ts`,
    `// Generated by scripts/data.ts from GeoThai/data ${version}. Do not edit.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(rows))}) as ${type}[];\n`,
  );
}

const names = (rows: Row[]) => rows.map((r) => [r.code, r.name_th, r.name_en]);

const provinces = await get<Row[]>('json/provinces.json');
const districts = await get<(Row & { province_code: string })[]>('json/districts.json');
// The package reads each parent from the start of a code, so check that the data agrees.
const strayDistrict = districts.find((d) => !d.code.startsWith(d.province_code));
if (strayDistrict) {
  throw new Error(`district ${strayDistrict.code} is not under ${strayDistrict.province_code}`);
}

const subdistricts =
  await get<(Row & { district_code: string; postal_codes: string[] })[]>('json/subdistricts.json');
const straySubdistrict = subdistricts.find((s) => !s.code.startsWith(s.district_code));
if (straySubdistrict) {
  throw new Error(
    `subdistrict ${straySubdistrict.code} is not under ${straySubdistrict.district_code}`,
  );
}

await write('provinces', names(provinces), '[string, string, string]');
await write('districts', names(districts), '[string, string, string]');
await write(
  'subdistricts',
  subdistricts.map((s) => [s.code, s.name_th, s.name_en, s.postal_codes.join(' ')]),
  '[string, string, string, string]',
);
console.log(
  `GeoThai/data ${version}: ${provinces.length} provinces, ${districts.length} districts, ${subdistricts.length} subdistricts`,
);
